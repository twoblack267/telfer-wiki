/**
 * check-rendered-layout.mjs
 * ─────────────────────────
 * Rendered-layout guard for the Telfer Wiki build.
 *
 * WHY IT EXISTS
 *   A prior bug put the SEO "Common Questions" (FAQ) and story-blurb blocks
 *   ABOVE the page's <h1> (the person's name), pushing the actual title below
 *   the fold on mobile. CI validated data and links but said nothing about the
 *   RENDERED page structure — so a "back-to-front" page shipped without a peep.
 *
 *   This guard scans every generated person page in dist/ and fails the build
 *   if the person's own <h1> heading is not the FIRST heading on the page.
 *   SEO/helper blocks (FAQ, story blurb) must appear AFTER it.
 *
 * WHAT IT CHECKS
 *   For each dist/people/<slug>/index.html:
 *     - REQUIRES exactly one <h1> (the person's display name).
 *     - REQUIRES the <h1> appears at an EARLIER byte offset than every <h2>
 *       and every "Common Questions"/"Their Story" helper block.
 *
 * FAILURE MODE
 *   Non-zero exit + a clear list of offending pages -> fails npm run postbuild
 *   -> blocks the GitHub Pages deploy. The build must not ship a page whose
 *   heading is buried.
 *
 * USAGE
 *   node scripts/check-rendered-layout.mjs   (called from package.json postbuild)
 *   Optional: node scripts/check-rendered-layout.mjs --dir dist
 */

import { readdirSync, readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.cwd();
const DIST = process.argv.includes('--dir')
  ? join(ROOT, process.argv[process.argv.indexOf('--dir') + 1])
  : join(ROOT, 'dist');

const PEOPLE_DIR = join(DIST, 'people');
if (!existsSync(PEOPLE_DIR)) {
  console.error(`[check-rendered-layout] no ${PEOPLE_DIR} — run astro build first`);
  process.exit(1);
}

const HELPER_MARKERS = ['Common Questions', 'Their Story', 'Frequently asked questions'];

/** Pull the raw <h1 …>…</h1> content and its byte offset. */
function firstH1(html) {
  const m = /<h1[^>]*>([\s\S]*?)<\/h1>/i.exec(html);
  if (!m) return null;
  const offset = m.index;
  const text = m[1].replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim();
  return { offset, text };
}

/** Byte offset of the first occurrence of a case-insensitive needle. */
function offsetOf(html, needle) {
  const i = html.toLowerCase().indexOf(needle.toLowerCase());
  return i === -1 ? null : i;
}

/** Byte offset of the first <h2 …>…</h2> block, or null. */
function firstH2(html) {
  const m = /<h2\b/i.exec(html);
  return m ? m.index : null;
}

const offenders = [];

const slugs = readdirSync(PEOPLE_DIR, { withFileTypes: true })
  .filter((e) => e.isDirectory())
  .map((e) => e.name);

for (const slug of slugs) {
  const file = join(PEOPLE_DIR, slug, 'index.html');
  if (!existsSync(file)) continue;
  const html = readFileSync(file, 'utf8');

  // Redirect stubs (legacy/duplicate slug aliases generated by
  // generate-redirects.mjs) are intentionally tiny meta-refresh pages with no
  // <h1> — they bounce to the canonical page. Skip them entirely.
  if (html.includes('http-equiv="refresh"') || html.includes('http-equiv=refresh')) {
    continue;
  }

  const h1 = firstH1(html);
  if (!h1) {
    // A person page with NO <h1> at all is a more serious structural bug.
    offenders.push({ slug, reason: 'no <h1> heading found on page' });
    continue;
  }

  // The person's own heading must come first.
  const h2 = firstH2(html);
  if (h2 !== null && h1.offset > h2) {
    offenders.push({
      slug,
      reason: `<h1> ("${h1.text}") appears AFTER first <h2> (offset ${h1.offset} > ${h2})`,
    });
    continue;
  }

  // No SEO/helper block may sit above the heading.
  for (const marker of HELPER_MARKERS) {
    const at = offsetOf(html, marker);
    if (at !== null && at < h1.offset) {
      offenders.push({
        slug,
        reason: `"${marker}" block appears at offset ${at}, BEFORE the <h1> at ${h1.offset}`,
      });
      break;
    }
  }
}

if (offenders.length === 0) {
  console.log(`🌳 check-rendered-layout: ${slugs.length} person pages — every <h1> is the first heading. CLEAN`);
  process.exit(0);
}

console.error(`🌳 check-rendered-layout: ${offenders.length} page(s) have a BURIED or MISSING title heading:`);
for (const o of offenders) {
  console.error(`   ❌ ${o.slug}: ${o.reason}`);
}
console.error(
  '\nThe person’s <h1> name must be the FIRST heading. ' +
    'Move SEO/FAQ/story blocks below the page content. Not fixing — refusing to ship.'
);
process.exit(1);
